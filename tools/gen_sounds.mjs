#!/usr/bin/env node
// Generates the sketch's sounds.h (built-in sound effects for sound.cpp) from shared/sounds.json.
// Shared verbatim by every app on this base: the sketch is the only folder under firmware/ that
// holds a <name>/<name>.ino. Each entry is {name, tempo, notes} in the melody format of sound.h;
// other fields (descriptions for the docs, the landing or the MCP) are ignored here.
// --check: fails when the committed header does not match the JSON.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sketches = readdirSync(join(root, 'firmware'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, 'firmware', d.name, `${d.name}.ino`)))
  .map((d) => d.name);
if (sketches.length !== 1) throw new Error(`expected one sketch under firmware/, found ${sketches.length}`);
const rel = `firmware/${sketches[0]}/sounds.h`;

const sounds = JSON.parse(readFileSync(join(root, 'shared/sounds.json'), 'utf8')).sfx;
const seen = new Set();
for (const s of sounds) {
  if (!/^[a-z][a-z0-9_]*$/.test(s.name) || s.name === 'count' || !s.notes || !(s.tempo >= 20 && s.tempo <= 400) ||
      /[^\x20-\x7e]/.test(s.notes))
    throw new Error(`sound ${s.name}: needs a lowercase name (not "count"), ASCII notes and tempo 20-400`);
  if (seen.has(s.name)) throw new Error(`sound ${s.name} is listed twice`);
  seen.add(s.name);
}
if (sounds.length > 255) throw new Error('at most 255 sound effects');

const cstr = (v) => JSON.stringify(v);  // JSON string escaping is valid C for these ASCII strings
const header = `// GENERATED by tools/gen_sounds.mjs from shared/sounds.json. Do not edit; run \`make gen\`.
// Built-in sound effects in the melody format of sound.h; play them with soundPlaySfx(SFX_<NAME>).
#pragma once
#include <stdint.h>

struct SfxDef {
  const char *name;
  uint16_t tempo;
  const char *notes;
};

enum SfxId : uint8_t {
${sounds.map((s) => `  SFX_${s.name.toUpperCase()},`).join('\n')}
  SFX_COUNT
};

static const SfxDef SFX[SFX_COUNT] = {
${sounds.map((s) => `    {${cstr(s.name)}, ${s.tempo}, ${cstr(s.notes)}},`).join('\n')}
};
`;

const file = join(root, rel);
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== header) {
    console.error(`${rel} is stale: run make gen`);
    process.exit(1);
  }
  console.log(`${rel} up to date`);
} else {
  writeFileSync(file, header);
  console.log(`${rel}: ${sounds.length} sound effects`);
}
