#!/usr/bin/env node
// Embeds web/index.html (and any extra file the app asks for) gzipped into the sketch's
// web_assets.h, as PROGMEM arrays NAME[] plus NAME_LEN. Shared verbatim by every app on this
// base: the sketch is the only folder under firmware/ that holds a <name>/<name>.ino.
//
// Usage: node tools/gen_web.mjs [--check] [NAME=path ...]
//   web/index.html is always embedded as WEB_INDEX_GZ; each NAME=path adds one more array
//   (the Makefile passes them through WEB_EMBED, so run it with `make gen` / `make check`).
// --check: fails when the committed header does not match the sources. It compares the
// *decompressed* content, not the gzip bytes: different zlib builds (macOS vs the Linux runner)
// produce different streams for the same input, which would make CI red for nothing.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { gzipSync, gunzipSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sketches = readdirSync(join(root, 'firmware'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, 'firmware', d.name, `${d.name}.ino`)))
  .map((d) => d.name);
if (sketches.length !== 1) throw new Error(`expected one sketch under firmware/, found ${sketches.length}`);
const rel = `firmware/${sketches[0]}/web_assets.h`;
const out = join(root, rel);

const args = process.argv.slice(2);
const check = args.includes('--check');
const assets = [['WEB_INDEX_GZ', 'web/index.html']];
for (const a of args.filter((x) => x !== '--check')) {
  const m = a.match(/^([A-Z][A-Z0-9_]*)=(.+)$/);
  if (!m) throw new Error(`bad argument ${a}: expected NAME=path`);
  if (assets.some(([name]) => name === m[1])) throw new Error(`${m[1]} is listed twice`);
  assets.push([m[1], m[2]]);
}

if (check) {
  const fail = (why) => {
    console.error(`${rel} is out of date (${why}): run \`make gen\` and commit the result`);
    process.exit(1);
  };
  if (!existsSync(out)) fail('missing');
  const committed = readFileSync(out, 'utf8');
  const names = [...committed.matchAll(/static const uint8_t (\w+)\[\] PROGMEM/g)].map((m) => m[1]);
  if (names.join() !== assets.map(([name]) => name).join()) fail(`arrays ${names.join(', ')}`);
  for (const [name, path] of assets) {
    const re = new RegExp(`static const uint8_t ${name}\\[\\] PROGMEM = \\{([\\d,\\s]*)\\};\\nstatic const size_t ${name}_LEN = (\\d+);`);
    const m = committed.match(re);
    if (!m) fail(`${name} not found`);
    const bytes = Buffer.from(m[1].split(',').map((v) => v.trim()).filter(Boolean).map(Number));
    if (bytes.length !== Number(m[2])) fail(`${name} length mismatch`);
    let inflated;
    try { inflated = gunzipSync(bytes); } catch { fail(`${name} is not valid gzip`); }
    if (!inflated.equals(readFileSync(join(root, path)))) fail(`${path} changed`);
  }
  console.log('web_assets.h up to date');
  process.exit(0);
}

let h = `// GENERATED by tools/gen_web.mjs. Do not edit; run \`make gen\`.\n` +
  `#pragma once\n#include <stdint.h>\n#include <stddef.h>\n#include <pgmspace.h>\n\n`;
for (const [name, path] of assets) {
  const raw = readFileSync(join(root, path));
  const gz = gzipSync(raw, { level: 9 });
  h += `// ${path}: ${raw.length} bytes -> ${gz.length} bytes gzip\nstatic const uint8_t ${name}[] PROGMEM = {\n`;
  for (let i = 0; i < gz.length; i += 24) h += '  ' + Array.from(gz.subarray(i, i + 24)).join(',') + ',\n';
  h += `};\nstatic const size_t ${name}_LEN = ${gz.length};\n\n`;
  console.log(`${path}: ${raw.length} -> ${gz.length} bytes gzip`);
}
writeFileSync(out, h);
console.log(`wrote ${rel}`);
